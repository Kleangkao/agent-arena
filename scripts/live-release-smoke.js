async page => {
 const out='evidence/final-integration/';
 const context=await page.context().browser().newContext({viewport:{width:390,height:844},recordVideo:{dir:out,size:{width:390,height:844}}});
 const live=await context.newPage();
 const error=[];
 const posts=[];
 live.on('pageerror',e=>error.push(e.message));
 live.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/api/matches'))posts.push(JSON.parse(r.postData()).requestId)});
 const click=name=>live.getByRole('button',{name,exact:true}).click();
 const shot=name=>live.screenshot({path:out+name,fullPage:true});
 const result=()=>live.getByRole('heading',{name:/^(Victory|Defeat|Draw)$/}).waitFor({timeout:85000});
 const meter=()=>live.locator('meter').evaluateAll(els=>els.map(el=>el.value));
 await live.goto('http://127.0.0.1:5173/');
 await click('My Agent');
 await live.getByRole('textbox',{name:'Coaching message'}).fill('Use ammo deliberately. Keep competing until the last turn.');
 await click('SAVE COACHING ↗');
 await live.getByText('Coaching saved for your next match.').waitFor();
 await shot('mobile-coaching.png');
 await click('Choose opponent →');
 await click('Fast-paced');
 await shot('mobile-opponent.png');
 const created=live.waitForResponse(r=>r.url().endsWith('/api/matches')&&r.request().method()==='POST')
  .then(async response=>({status:response.status(),id:(await response.json()).id}));
 await click('CHALLENGE ↗');
 await live.getByText('Preparing the match…').waitFor();
 const {id,status}=await created;
 if(status!==202)throw Error('Match was not accepted '+status);
 await shot('mobile-preparation.png');
 await click('BACK TO ARENA');
 await live.reload();
 await click('Arena');
 await click('REOPEN YOUR MATCH');
 await live.getByText('Turn 3 / 10',{exact:true}).waitFor({timeout:85000});
 await shot('mobile-live-battle.png');
 await result();
 const hp=await meter();
 await shot('mobile-live-result.png');
 await live.getByText('Agent lesson',{exact:true}).waitFor({timeout:18000});
 await shot('mobile-live-lesson.png');
 await live.locator('.canvas canvas').screenshot({path:out+'terminal-normal-canvas.png'});
 await live.reload();
 await click('Arena');
 await click('REOPEN YOUR MATCH');
 await click('PAUSE');
 await click('SKIP TO RESULT');
 await result();
 if(JSON.stringify(await meter())!==JSON.stringify(hp))throw Error('Recovered result changed');
 await live.locator('.canvas canvas').screenshot({path:out+'terminal-recovered-canvas.png'});
 await shot('mobile-recovered-result.png');
 await click('Coach Agent →');
 await live.getByText('Memory',{exact:true}).click();
 await live.locator('.coach li').first().waitFor();
 await live.getByText('Agent Passport',{exact:true}).click();
 await shot('mobile-memory-passport.png');
 if(await live.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 if(new Set(posts).size!==1||error.length)throw Error(JSON.stringify({posts:posts.length,errors:error}));
 const video=live.video();
 await context.close();
 await video.saveAs(out+'latest-local-gemini-mobile.webm');
 await video.delete();
 console.log(JSON.stringify({matchId:id,hp,matchPostCount:posts.length,uniqueRequestIds:new Set(posts).size}));
}
